def build_workbook(path: str) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = BUILDING

    # --- 標題列 ---
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(HEADERS))
    title_cell = ws.cell(row=1, column=1, value=f"{BUILDING} 櫃檯服務備忘錄（113.02.28 更新）")
    title_cell.font = Font(name="微軟正黑體", size=16, bold=True, color="FFFFFF")
    title_cell.alignment = Alignment(horizontal="center", vertical="center")
    title_cell.fill = PatternFill("solid", fgColor="305496")
    ws.row_dimensions[1].height = 30

    # --- 欄位列 ---
    header_fill = PatternFill("solid", fgColor="8EA9DB")
    header_font = Font(name="微軟正黑體", size=11, bold=True, color="FFFFFF")
    center = Alignment(horizontal="center", vertical="center", wrap_text=True)
    thin = Side(border_style="thin", color="808080")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    for col_idx, header in enumerate(HEADERS, start=1):
        cell = ws.cell(row=2, column=col_idx, value=header)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = center
        cell.border = border
    ws.row_dimensions[2].height = 28

    # --- 資料列 ---
    body_font = Font(name="微軟正黑體", size=10)
    body_align = Alignment(horizontal="left", vertical="center", wrap_text=True)
    center_align = Alignment(horizontal="center", vertical="center", wrap_text=True)
    parking_fill = PatternFill("solid", fgColor="D9E1F2")
    zebra_fill = PatternFill("solid", fgColor="F2F2F2")

    for i, row in enumerate(ROWS, start=3):
        no, unit, owner, phone, p1, p2, p3, p4, note = row
        values = [BUILDING, no, unit, owner, phone, p1, p2, p3, p4, note]
        for col_idx, value in enumerate(values, start=1):
            cell = ws.cell(row=i, column=col_idx, value=value)
            cell.font = body_font
            cell.border = border
            if col_idx in (1, 2, 3, 6, 7, 8, 9):  # 大樓/編號/戶別/車位 置中
                cell.alignment = center_align
            else:
                cell.alignment = body_align
            if col_idx in (6, 7, 8, 9) and value not in ("", None):
                cell.fill = parking_fill
            elif (i % 2) == 0:
                cell.fill = zebra_fill

    # --- 欄寬 ---
    widths = {
        "A": 8,   # 大樓
        "B": 6,   # 編號
        "C": 12,  # 戶別
        "D": 22,  # 所有權人
        "E": 38,  # 聯絡電話
        "F": 8,   # 車位1
        "G": 8,   # 車位2
        "H": 8,   # 車位3
        "I": 8,   # 車位4
        "J": 22,  # 備註
    }
    for col, w in widths.items():
        ws.column_dimensions[col].width = w

    # --- 凍結窗格 + 篩選 ---
    ws.freeze_panes = "A3"
    ws.auto_filter.ref = f"A2:{get_column_letter(len(HEADERS))}{len(ROWS) + 2}"

    # --- 統計表（簡易資訊頁） ---
    info = wb.create_sheet("使用說明")
    notes = [
        ["時光嶼櫃檯服務備忘錄 - 統一格式說明", ""],
        ["更新日期", "113.02.28（依原稿）"],
        ["", ""],
        ["欄位", "說明"],
        ["大樓", "棟別名稱（方便後續多棟合併使用）"],
        ["編號", "原稿流水號"],
        ["戶別", "如 3B1、3+4B5、S5 等（同戶別跨樓層以 + 連接）"],
        ["所有權人", "屋主姓名；如為出租，註明「租-OOO」或「前/新屋主」"],
        ["聯絡電話", "多支電話以「 / 」分隔，括號內為關係（夫/妻/父/母/同住等）；無電話統一填 0-"],
        ["車位1~4", "車位編號；無則留空（最多 4 個）"],
        ["備註", "出租中、屋主更換、職務（財委/監委）等補充事項"],
        ["", ""],
        ["後續其他棟使用建議", "直接在本工作簿新增工作表（例：時光嶼 B 棟、時光嶼 C 棟）"],
        ["", "或在本表續加列，於「大樓」欄填入對應棟名後即可一起篩選與彙整"],
        ["", ""],
        ["待補/待確認", "編號 83（7B3 吳弘信）車位編號原稿不清，請複核"],
        ["", "編號 104（10B8 王聿杰）電話空白，請補上"],
    ]
    for r, (a, b) in enumerate(notes, start=1):
        ca = info.cell(row=r, column=1, value=a)
        cb = info.cell(row=r, column=2, value=b)
        ca.font = Font(name="微軟正黑體", size=11, bold=(r in (1, 4)))
        cb.font = Font(name="微軟正黑體", size=11)
        ca.alignment = Alignment(vertical="top", wrap_text=True)
        cb.alignment = Alignment(vertical="top", wrap_text=True)
    info.column_dimensions["A"].width = 22
    info.column_dimensions["B"].width = 60

    wb.save(path)


